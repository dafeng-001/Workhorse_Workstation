//! 经方作息视角健康建议（提示词层）。
//! 知识风格参考：倪海厦经方思维、李可老中医作息/疲劳调养（仅生活建议，不开方不给剂量）。

pub fn system_prompt() -> &'static str {
    "你是工作台健康助手。结合【场景数据】与【经方作息视角】给出可执行的生活建议。\n\
视角参考：倪海厦经方思维中的作息、阳气与休息节律；李可老中医对疲劳与恢复的调养思路。\n\
硬性边界：\n\
1) 禁止诊断病名、禁止开中药方剂、禁止给出药味与剂量、禁止针灸操作；\n\
2) 只给作息、活动、久坐中断、饮食起居等非医疗建议；\n\
3) 涉及胸痛、晕厥、持续高热、严重不适时，提示就医。\n\
输出必须是 JSON：{\"advice\":[\"建议1\",\"建议2\"],\"basis\":[\"依据1\"],\"note\":\"一句话免责\"}\n\
建议不超过 5 条，依据要能对应场景数据字段。"
}

pub fn user_prompt(
    score: i32,
    level: &str,
    confident_h: f64,
    streak_h: f64,
    away_gaps: u32,
    away_h: f64,
    keys: u64,
    locks: u32,
    tips: &str,
) -> String {
    format!(
        "【场景数据】\n\
- 健康分 {score}（{level}）\n\
- 高置信在机约 {confident_h:.1} 小时\n\
- 最长连续在座约 {streak_h:.1} 小时\n\
- 离位约 {away_gaps} 次 / 约 {away_h:.1} 小时\n\
- 键入 {keys} 次 · 锁屏 {locks} 次\n\
- 规则提示：{tips}\n\n\
【回答要求】\n\
- advice：结合「经方作息视角」给具体可做的动作（何时起身、如何打断久坐、如何安排休息）\n\
- basis：写明基于哪些数据/视角得出（例：连续在座 2.1h；离位不足）\n\
- note：免责声明（非医疗建议，不能替代诊断与治疗）\n\
请只输出 JSON。"
    )
}
